def get_athlete_level(metric: str, value: float, gender: str, sport: str) -> Dict[str, Any]:
    """根据指标值和性别/项目确定运动员等级"""
    sport_std = SPORT_STANDARDS.get(sport, SPORT_STANDARDS["其他"])
    metric_std = sport_std.get(metric)
    if not metric_std:
        return {"level": "未知", "index": -1, "next_level": None, "gap": None}

    gender_key = "男" if gender == "男" else "女"
    thresholds = metric_std.get(gender_key, metric_std.get("男", []))

    is_lower_better = "sprint" in metric.lower() or "冲刺" in metric

    current_level = 0  # 0=未达标, 1=爱好者, 2=二级, 3=一级, 4=健将
    for i, threshold in enumerate(thresholds):
        if is_lower_better:
            if value <= threshold:
                current_level = i + 1
        else:
            if value >= threshold:
                current_level = i + 1

    level_names = ["未达标"] + LEVELS
    level_name = level_names[current_level]
    next_level = level_names[current_level + 1] if current_level < 4 else None
    gap = None
    if next_level and current_level < 4:
        next_threshold = thresholds[current_level]
        gap = abs(value - next_threshold)

    return {
        "level": level_name,
        "level_index": current_level,
        "next_level": next_level,
        "gap_to_next": round(gap, 2) if gap is not None else None,
        "is_lower_better": is_lower_better,
    }


def get_sport_standards(sport: str) -> Dict:
    """获取指定项目的全部标准"""
    return SPORT_STANDARDS.get(sport, SPORT_STANDARDS["其他"])
